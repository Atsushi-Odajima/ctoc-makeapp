"""Build the self-hosted WOFF2 subsets and src/app/fonts.css.

Usage (Python 3 + fonttools + brotli):
    python scripts/fonts/subset_fonts.py <dir with the TTFs from github.com/google/fonts>

Sources (SIL Open Font License 1.1; licence texts are copied to public/fonts/*-OFL.txt):
    ofl/zenkakugothicnew/ZenKakuGothicNew-{Regular,Medium,Bold}.ttf
    ofl/barlowcondensed/BarlowCondensed-{Medium,SemiBold}.ttf

Japanese: zen-kaku-gothic-new-slices.txt holds one unicode-range per line, taken from the
Google Fonts CSS API for this family (its frequency-ordered slicing). Each slice becomes its own
WOFF2, so a page downloads only the slices for the characters it actually renders instead of a
whole multi-megabyte weight. Barlow Condensed is used for short Latin labels only, so it ships a
single Latin subset.
"""
import os
import sys
from concurrent.futures import ProcessPoolExecutor

from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "public", "fonts")
CSS = os.path.join(ROOT, "src", "app", "fonts.css")

JA_WEIGHTS = [("Regular", 400), ("Medium", 500), ("Bold", 700)]
LATIN_WEIGHTS = [("Medium", 500), ("SemiBold", 600)]
LATIN_RANGE = "U+0020-007E,U+00A0-00FF,U+2010-2027,U+2030-205E,U+20AC,U+2122"


def parse_range(text):
    codes = []
    for part in text.replace(" ", "").split(","):
        if not part:
            continue
        lo, _, hi = part[2:].partition("-")
        codes.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return codes


def build(job):
    src, dest, urange = job
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = subset.load_font(src, options)
    sub = subset.Subsetter(options)
    sub.populate(unicodes=parse_range(urange))
    sub.subset(font)
    if not font["cmap"].getBestCmap():
        return None  # the font has no glyphs in this slice
    subset.save_font(font, dest, options)
    return dest


def face(family, url, weight, urange):
    return (f"@font-face{{font-family:'{family}';src:url('{url}') format('woff2');font-weight:{weight};"
            f"font-style:normal;font-display:swap;unicode-range:{urange.replace(' ', '')}}}")


def main(src_dir):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(HERE, "zen-kaku-gothic-new-slices.txt"), encoding="utf-8") as f:
        slices = [line.strip() for line in f if line.strip()]
    jobs, rules = [], []
    for style, weight in JA_WEIGHTS:
        for i, urange in enumerate(slices):
            name = f"zkgn-{weight}-{i:03d}.woff2"
            jobs.append((os.path.join(src_dir, f"ZenKakuGothicNew-{style}.ttf"), os.path.join(OUT, name), urange))
            rules.append(("Zen Kaku Gothic New", f"/fonts/{name}", weight, urange))
    for style, weight in LATIN_WEIGHTS:
        name = f"barlow-condensed-{weight}-latin.woff2"
        jobs.append((os.path.join(src_dir, f"BarlowCondensed-{style}.ttf"), os.path.join(OUT, name), LATIN_RANGE))
        rules.append(("Barlow Condensed", f"/fonts/{name}", weight, LATIN_RANGE))
    with ProcessPoolExecutor() as pool:
        built = set(filter(None, pool.map(build, jobs)))
    css = [face(fam, url, w, r) for fam, url, w, r in rules if os.path.join(OUT, os.path.basename(url)) in built]
    header = (
        "/* DayNet fonts — self-hosted, generated by scripts/fonts/subset_fonts.py (do not edit by hand).\n"
        "   Zen Kaku Gothic New 400/500/700: all Japanese UI and text, sliced by unicode-range so only the\n"
        "   slices a page renders are downloaded. Barlow Condensed 500/600: short Latin labels only.\n"
        "   Both SIL Open Font License 1.1 (/fonts/*-OFL.txt). font-display: swap; the system font\n"
        "   stack in globals.css stays as the fallback for loading failures and missing glyphs. */\n"
    )
    with open(CSS, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(css) + "\n")
    print(f"{len(built)} files, {sum(os.path.getsize(p) for p in built) // 1024} KB total")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
